#!/usr/bin/env python3
"""
lexdfa.py -- reconstruct the flex lexer DFA out of wishd201.exe and
enumerate its complete token set.

The scripting language has NO keyword string table; flex encodes the
keywords in its DFA transition tables. This script embeds those tables,
simulates the standard flex inner loop, and walks the automaton to
recover every accepting rule and its shortest spelling.

Table addresses in wishd201.exe:

    yy_accept  00420528  words
    yy_ec      00420640  32-bit entries, low byte used
    yy_meta    00420a40  32-bit entries, low byte used
    yy_base    00420b18  words
    yy_def     00420c38  words
    yy_nxt     00420d58  words
    yy_chk     00420f00  words, ends exactly where "parse error" begins

Only yy_ec for printable ASCII (0x20..0x7E) is embedded, so rules keyed
on newline or tab are not enumerated.

Usage:  python tools/lexdfa.py
"""
import binascii, collections

def w16(h):
    b = binascii.unhexlify(h)
    return [b[i] | (b[i+1] << 8) for i in range(0, len(b), 2)]

