yy_ec = {}
for i, v in enumerate(_ec):
    yy_ec[chr(0x20 + i)] = v

JAM = 136

def step(state, ch):
    c = yy_ec.get(ch)
    if c is None:
        return None
    while True:
        idx = yy_base[state] + c
        if idx < len(yy_chk) and yy_chk[idx] == state:
            break
        state = yy_def[state]
        if state >= JAM:
            c = yy_meta[c]
        if state == 0:
            return None
    idx = yy_base[state] + c
    if idx >= len(yy_nxt):
        return None
    ns = yy_nxt[idx]
    return None if ns >= JAM else ns

def run(s, start=1):
    st = start
    for ch in s:
        st = step(st, ch)
        if st is None:
            return None
    return st

def acc(st):
    return yy_accept[st] if st is not None and st < len(yy_accept) else 0

# Identify the identifier rule by probing a name that cannot be a keyword.
ident_rule = acc(run("zzq"))
print("identifier rule =", ident_rule)
print("sanity: 'foo' ->", acc(run("foo")), " 'x' ->", acc(run("x")))

# Full token enumeration: BFS over every printable character, visiting
# each state once with its shortest spelling.
ALPHA = "".join(chr(c) for c in range(0x20, 0x7f))
best = {}
q = collections.deque([("", 1)])
best[1] = ""
while q:
    st_s, st = q.popleft()
    for ch in ALPHA:
        ns = step(st, ch)
        if ns is not None and ns not in best:
            best[ns] = st_s + ch
            q.append((st_s + ch, ns))

rules = {}
for st, word in best.items():
    a = acc(st)
    if word and a:
        if a not in rules or len(word) < len(rules[a]):
            rules[a] = word
print()
print("states reached:", len(best), " distinct accepting rules:", len(rules))
print()
for a in sorted(rules):
    tag = "  <- identifier" if a == ident_rule else ""
    print("   rule %-3d  %r%s" % (a, rules[a], tag))
